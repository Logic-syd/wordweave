export function expressionMeanings(expression: string): string[] {
  const text = expression.toLowerCase();
  const avoid = text.match(/^avoid(?:s|ed|ing)? unnecessary (.+)$/);
  if (avoid) {
    const objects: Record<string, string[]> = {
      "re-renders": ["重新渲染", "重渲染"],
      renders: ["渲染"],
      requests: ["请求"],
      work: ["工作"],
      updates: ["更新"],
      complexity: ["复杂性", "复杂度"],
    };
    return (objects[avoid[1]] ?? []).map((object) => `避免不必要的${object}`);
  }
  if (/^introduc(?:e|es|ed|ing) (?:a )?breaking changes?$/.test(text))
    return ["引入破坏性更改", "引入重大更改", "引入破坏性变更"];
  if (/^tak(?:e|es|ing) advantage of$/.test(text)) return ["利用"];
  if (/^tak(?:e|es|ing) into account$/.test(text)) return ["考虑到", "考虑"];
  if (/^keep(?:s|ing)? in mind$/.test(text)) return ["记住", "牢记"];
  if (/^keep(?:s|ing)? track of$/.test(text)) return ["跟踪", "追踪", "记录"];
  return (
    meanings[text] ??
    meanings[text.replace(/ies$/, "y")] ??
    meanings[text.replace(/s$/, "")] ??
    []
  );
}
